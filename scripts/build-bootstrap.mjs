// Regenerate supabase/bootstrap/01_schema_part*.sql from the migration
// history, dropping statements that touch MASTER-OPS-only tables.
//
// Those statements (policies on critical_dates / snapshots / sent_alerts, and
// an alter on critical_dates) were no-ops-with-purpose in the SHARED database,
// where Master-Ops owned those tables. On a standalone CardOps project they
// reference relations that will never exist, so the whole script aborts. They
// carry nothing CardOps needs — dropping them is exactly right for a fresh
// install, and the historical migrations stay untouched as the record of what
// the shared DB actually ran.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const MIGRATIONS = "supabase/migrations";
const OUT = "supabase/bootstrap";
const FOREIGN = /public\.(critical_dates|snapshots|sent_alerts)\b/;

/** Split SQL into statements, respecting $$ / $tag$ dollar-quoted bodies. */
function statements(sql) {
  const out = [];
  let buf = "";
  let tag = null;
  for (let i = 0; i < sql.length; i++) {
    const rest = sql.slice(i);
    if (!tag) {
      const m = /^\$([A-Za-z_]*)\$/.exec(rest);
      if (m) { tag = m[0]; buf += m[0]; i += m[0].length - 1; continue; }
      if (sql[i] === ";") { buf += ";"; out.push(buf); buf = ""; continue; }
    } else if (rest.startsWith(tag)) {
      buf += tag; i += tag.length - 1; tag = null; continue;
    }
    buf += sql[i];
  }
  if (buf.trim()) out.push(buf);
  return out;
}

const files = readdirSync(MIGRATIONS).filter((f) => f.endsWith(".sql")).sort();
const kept = [];
let dropped = 0;
for (const f of files) {
  const text = readFileSync(join(MIGRATIONS, f), "utf8");
  const stmts = statements(text).filter((s) => {
    if (!FOREIGN.test(s)) return true;
    // Keep any statement that CREATES something of ours mentioning them
    // (none today) — drop policy/alter chatter about foreign tables.
    if (/^\s*(--[^\n]*\n\s*)*(drop\s+policy|create\s+policy|alter\s+table)/i.test(s)) { dropped++; return false; }
    return true;
  });
  kept.push({ file: f, sql: stmts.join("").trim() });
}

const parts = [[], [], []];
const sizes = [0, 0, 0];
let idx = 0;
for (const { file, sql } of kept) {
  if (sizes[idx] > 55_000 && idx < 2) idx++;
  parts[idx].push(`-- ═══════════ ${file} ═══════════\n${sql}\n`);
  sizes[idx] += sql.length;
}
parts.forEach((p, i) => {
  const header =
    "-- ══════════════════════════════════════════════════════════════════════════\n" +
    `-- STANDALONE BOOTSTRAP · STEP ${i + 1} of 3 — the CardOps migration history,\n` +
    "-- concatenated in order, with Master-Ops-only table chatter removed.\n" +
    `-- Run AFTER 00_foundations.sql${i > 0 ? ` and part ${i}` : ""}.\n` +
    "-- Generated by scripts/build-bootstrap.mjs — do not hand-edit.\n" +
    "-- ══════════════════════════════════════════════════════════════════════════\n\n";
  writeFileSync(join(OUT, `01_schema_part${i + 1}.sql`), header + p.join("\n"));
  console.log(`part${i + 1}: ${p.length} migrations, ${Math.round(sizes[i] / 1024)}KB`);
});
console.log(`dropped ${dropped} Master-Ops-only statements`);
